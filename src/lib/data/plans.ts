/** Approve a draft plan and send it to the client. Archives previous current plans. */
export async function activatePlan(planId: string, clientId: string) {
 if (isSupabaseConfigured && supabase) {
 // Archive existing current plans of the same client+type
 const { data: plan } = await supabase
 .from("plans")
 .select("type")
 .eq("id", planId)
 .maybeSingle();
 if (plan) {
 await supabase
 .from("plans")
 .update({ is_current: false, status: "archived" })
 .eq("client_id", clientId)
 .eq("type", plan.type)
 .eq("is_current", true)
 .neq("id", planId);
 }
 // Approve + activate
 const { data, error } = await supabase
 .from("plans")
 .update({
 status: "approved",
 is_current: true,
 approved_at: new Date().toISOString(),
 })
 .eq("id", planId)
 .select()
 .single();
 if (error) throw new Error(error.message);
 // Notify the client — 0093: payload feeds the bell's render-side catalog.
 // NOTIF→PLAN 2026-10-24 (items 1+3): (a) the emit is DEDUPED on
 // plan_id — the live DB showed the same approval firing 5-53s apart on
 // double-click/retry; (b) the link deep-opens THIS plan's modal
 // (/plans?plan=<id>) instead of dropping the member on the plans list.
 await createNotificationDeduped(
  clientId,
  "plan_activated",
  "تم تفعيل خطة جديدة لك! ",
  "خطتك الجديدة جاهزة الآن. اطّلع عليها من صفحة خططي.",
  `/plans?plan=${planId}`,
  { plan_type: plan?.type === "meal" ? "meal" : "workout", plan_id: planId },
  { key: "plan_id", value: planId, windowMs: 5 * 60 * 1000 },
 );
 // Notify coach (confirmation — routed to the client's assigned coach).
 // NOTIF→PLAN 2026-10-24 (item 3): the staff link opens the client's
 // manager page directly (/coach/<id>) instead of the generic coach list.
 await createAdminNotification(
  "plan_approved",
  "تم تفعيل خطة للعميل ",
  `خطة ${plan?.type === "meal" ? "تغذية" : "تمارين"} تم تفعيلها وإرسالها للعميل.`,
  `/coach/${clientId}`,
  clientId,
  { plan_type: plan?.type === "meal" ? "meal" : "workout", client_id: clientId, plan_id: planId, dedupKey: `plan_approved:${planId}` },
 ).catch(() => {});
 return data;
 }
 // Local fallback
 const all = read<Plan[]>(LS_PLANS, []);
 const idx = all.findIndex((p) => p.id === planId);
 if (idx >= 0) {
 all[idx].status = "approved";
 all[idx].is_current = true;
 all[idx].approved_at = new Date().toISOString();
 write(LS_PLANS, all);
 }
 return all[idx];
}

/**
 * Get current swap usage for display — T-AI-DEEP-AUDIT-V2 (D6 fix).
 * MUST mirror the ENFORCEMENT in tier-limits.ts / /api/ai/jobs exactly:
 *   - weekly Monday-anchored window (was: daily — stale legacy system)
 *   - limits from memberships.ts evoSwapLimit via the VERIFIED active
 *     subscription (was: swapLimitFor from the retired starter/elite
 *     tier system — "premium" resolved to undefined → showed UNLIMITED
 *     while the server enforced 3/week)
 */
export async function getSwapUsage(userId: string) {
 const userSub = await getSubscriptionForClient(userId);
 const tierId = (userSub?.tier ?? "free") as MembershipTier;
 const LIMIT = getLimits(tierId).evoSwapLimit; // number | null (null = unlimited)
 // Monday-anchored week start — byte-for-byte the same math as
 // tier-limits.countThisWeekSwaps, so display == enforcement.
 const now = new Date();
 const dayOfWeek = now.getDay(); // 0=Sun, 1=Mon, ...
 const mondayOffset = dayOfWeek === 0 ? 6 : dayOfWeek - 1;
 const weekStart = new Date(now);
 weekStart.setDate(now.getDate() - mondayOffset);
 weekStart.setHours(0, 0, 0, 0);
 if (isSupabaseConfigured && supabase) {
 const [meals, exercises] = await Promise.all([
 supabase
 .from("plan_swaps")
 .select("*", { count: "exact", head: true })
 .eq("user_id", userId)
 .eq("swap_type", "meal")
 .gte("created_at", weekStart.toISOString()),
 supabase
 .from("plan_swaps")
 .select("*", { count: "exact", head: true })
 .eq("user_id", userId)
 .eq("swap_type", "exercise")
 .gte("created_at", weekStart.toISOString()),
 ]);
 return {
 meal: {
 used: meals.count ?? 0,
 limit: LIMIT,
 remaining: LIMIT === null ? Infinity : Math.max(0, LIMIT - (meals.count ?? 0)),
 unlimited: LIMIT === null,
 },
 exercise: {
 used: exercises.count ?? 0,
 limit: LIMIT,
 remaining: LIMIT === null ? Infinity : Math.max(0, LIMIT - (exercises.count ?? 0)),
 unlimited: LIMIT === null,
 },
 };
 }
 return {
 meal: { used: 0, limit: LIMIT, remaining: LIMIT === null ? Infinity : LIMIT, unlimited: LIMIT === null },
 exercise: { used: 0, limit: LIMIT, remaining: LIMIT === null ? Infinity : LIMIT, unlimited: LIMIT === null },
 };
}

export async function addPlan(plan: PlanInsert): Promise<Plan> {
 if (isSupabaseConfigured && supabase) {
 // New plans from coach upload are "approved" directly (manual upload).
 // New plans from AI generation are "draft" (need approval).
 const status = plan.status || "approved";
 const is_current = plan.is_current ?? (status === "approved");
 const { data, error } = await supabase
 .from("plans")
 .insert({ ...plan, status, is_current })
 .select()
 .single();
 if (error) throw new Error(error.message);
 return data;
 }
 const all = read<Plan[]>(LS_PLANS, []);
 const status = plan.status || "approved";
 const newRow: Plan = {
 ...plan,
 id: uid(),
 notes: plan.notes ?? null,
 file_url: plan.file_url ?? null,
 content: plan.content ?? null,
 status,
 is_current: plan.is_current ?? (status === "approved"),
 approved_at: status === "approved" ? new Date().toISOString() : null,
 created_at: new Date().toISOString(),
 };
 all.push(newRow);
 write(LS_PLANS, all);
 return newRow;
}

/**
 * DRAFT-DELETE FIX 2026-10-24 (owner order item 3 «أضف وسيلة واضحة وآمنة
 * لحذف المسودة… مع تأكيد قبل الحذف، وتحقق من الملكية وصحة الحذف من
 * قاعدة البيانات وتحديث القائمة»): the old deletePlan fired the delete
 * and returned void — the Supabase error was DISCARDED, so a silently
 * failing delete (RLS, network, row already gone) looked exactly like a
 * success and the UI refreshed the list anyway. The contract is now
 * VERIFIED: the error is captured AND the row is confirmed gone (a fresh
 * RLS-visible select by id) before { ok: true } is returned — the caller
 * toasts the truth. Deletion touches ONLY the plans row: ai_jobs
 * receipts, plan_swaps history and notifications stay untouched.
 */
export async function deletePlan(
 id: string,
): Promise<{ ok: true } | { ok: false; error: string }> {
 if (isSupabaseConfigured && supabase) {
  const { error } = await supabase.from("plans").delete().eq("id", id);
  if (error) {
   console.error("[deletePlan] supabase delete failed:", error.message);
   return { ok: false, error: error.message };
  }
  // Verify-gone: RLS still shows the row to this coach if the delete
  // silently matched nothing (or was rolled back) — never claim success
  // over an unverifiable state.
  const { data: stillThere } = await supabase
   .from("plans")
   .select("id")
   .eq("id", id)
   .maybeSingle();
  if (stillThere) {
   return { ok: false, error: "تعذر حذف الخطة من قاعدة البيانات — حاول مرة أخرى" };
  }
  return { ok: true };
 }
 const all = read<Plan[]>(LS_PLANS, []);
 const next = all.filter((p) => p.id !== id);
 if (next.length === all.length) {
  return { ok: false, error: "الخطة غير موجودة — حدّث الصفحة" };
 }
 write(LS_PLANS, next);
 return { ok: true };
}

/** Update a plan's content (title, notes, content JSON, status). */
export async function updatePlan(id: string, updates: { title?: string; notes?: string; content?: PlanContent | null; status?: string; is_current?: boolean }): Promise<Plan | undefined> {
 if (isSupabaseConfigured && supabase) {
 const payload: PlanUpdate = {
 title: updates.title,
 notes: updates.notes,
 status: updates.status,
 is_current: updates.is_current,
 };
 if (updates.content !== undefined) {
 // Honest boundary cast: PlanContent (typed alias) → supabase Json.
 payload.content = updates.content as PlanUpdate["content"];
 }
 const { data, error } = await supabase
 .from("plans")
 .update(payload)
 .eq("id", id)
 .select()
 .single();
 if (error) throw new Error(error.message);
 return data;
 }
 const all = read<Plan[]>(LS_PLANS, []);
 const idx = all.findIndex((p) => p.id === id);
 if (idx >= 0) {
 const merged: Plan = { ...all[idx], ...updates };
 if (updates.content !== undefined) {
 merged.content = updates.content as Plan["content"];
 }
 all[idx] = merged;
 write(LS_PLANS, all);
 }
 return all[idx];
}

