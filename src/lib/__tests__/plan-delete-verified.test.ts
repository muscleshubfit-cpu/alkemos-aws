import { describe, it, expect, beforeEach } from "vitest";
import { deletePlan } from "@/lib/data/plans";
import { LS_PLANS } from "@/lib/data/helpers";
import type { Plan } from "@/lib/supabase/types";

/**
 * DRAFT-DELETE 2026-10-24 (owner order item 3 — «أضف وسيلة واضحة وآمنة
 * لحذف المسودة من الواجهة، مع تأكيد قبل الحذف، وتحقق من الملكية وصحة
 * الحذف من قاعدة البيانات وتحديث القائمة»): the verified deletePlan
 * contract. The old function fired the delete and returned VOID — a
 * silently failing delete (RLS / network / row already gone) looked
 * exactly like success and the UI refreshed the list anyway. The new
 * contract answers { ok } honestly; these canaries pin it on the
 * local-fallback path (the Supabase path runs the same verdict logic
 * through the RLS-visible verify-gone select — exercised live by the
 * coach UI in production).
 */

const planRow = (id: string, status: string): Plan => ({
  id,
  client_id: "client-1",
  type: "meal",
  title: `خطة ${id}`,
  notes: "Generated by AI",
  file_url: null,
  content: { overview: "", daily_calories: 2000, macros: { protein_g: 1, carbs_g: 1, fat_g: 1 }, meals: [] },
  status,
  is_current: false,
  approved_at: null,
  created_at: "2026-10-24T00:00:00Z",
});

describe("deletePlan — the verified contract (DRAFT-DELETE)", () => {
  beforeEach(() => {
    localStorage.clear();
  });
  it("deletes an existing row and reports ok:true honestly", async () => {
    localStorage.setItem(LS_PLANS, JSON.stringify([planRow("d1", "draft"), planRow("a1", "approved")]));
    const verdict = await deletePlan("d1");
    expect(verdict).toEqual({ ok: true });
    const left = JSON.parse(localStorage.getItem(LS_PLANS) || "[]") as Plan[];
    expect(left.map((p) => p.id)).toEqual(["a1"]);
  });

  it("a missing row reports ok:false — never a silent success", async () => {
    localStorage.setItem(LS_PLANS, JSON.stringify([planRow("a1", "approved")]));
    const verdict = await deletePlan("does-not-exist");
    expect(verdict.ok).toBe(false);
    if (!verdict.ok) expect(verdict.error).toBeTruthy();
    // and the existing row survives untouched
    const left = JSON.parse(localStorage.getItem(LS_PLANS) || "[]") as Plan[];
    expect(left.map((p) => p.id)).toEqual(["a1"]);
  });

  it("an empty store reports ok:false (not ok over nothing)", async () => {
    const verdict = await deletePlan("whatever");
    expect(verdict.ok).toBe(false);
  });

  it("deleting one draft never touches other plans or their statuses (blast-radius law)", async () => {
    const rows = [planRow("d1", "draft"), planRow("d2", "draft"), planRow("cur", "approved")];
    localStorage.setItem(LS_PLANS, JSON.stringify(rows));
    await deletePlan("d1");
    const left = JSON.parse(localStorage.getItem(LS_PLANS) || "[]") as Plan[];
    expect(left.map((p) => p.id).sort()).toEqual(["cur", "d2"]);
    expect(left.find((p) => p.id === "cur")?.status).toBe("approved");
  });
});
