import { describe, it, expect } from "vitest";
import { existsSync, readFileSync, statSync } from "node:fs";
import { resolve } from "node:path";
// The REAL emitted schema data — imported from the same modules the
// layouts render, so the canary guards the actual source (not a copy of
// it). Pure data modules (tools-shared.ts law), jsdom-safe.
import { getToolsHubItemList } from "@/lib/tools-hub-itemlist";
import { TOOLS } from "@/lib/tools-shared";

/**
 * ORGANIC-GROWTH-P0-F — the dedicated OG cards + tools-hub ItemList canary
 * (roadmap docs/organic-growth-system-2026-11-18/10 field 8: «فحص الحجم/
 * الأبعاد (1200×630) + JSON-LD صحيحة» and field 9: «6 بطاقات جديدة
 * مُشار إليها فعلًا بالكود + ItemList يتحقق آليًا» — both acceptance
 * criteria enforced as automated checks).
 *
 * The defect (audit 01/10-P0-F field 3):
 *   - The (en)/(ar) evo layouts PROMISED dedicated cards since Phase 231
 *     («the card is now the DEDICATED EVO card og-evo-en, 1200×630») while
 *     the URL pointed at og-home — the promised files did not exist (404).
 *   - All six surfaces (memberships/evo/tools ×2 languages) shared the
 *     generic homepage card (live-verified pre-frame: og-home on all six,
 *     dedicated card URLs 404).
 *   - The tools hub — the parent surface of the cluster holding ~75% of
 *     the site's measured impression footprint — carried NO parent schema.
 *
 * The fix (field 4): six cards generated by the existing
 * scripts/generate-og-cards.py (same og-home template — the SOCIAL-OG-3
 * visual law) + ItemList with the 8 hub tools on both /tools layouts,
 * built from the SAME TOOLS array the grid renders (tools-shared.ts).
 *
 * Previous-law preservation (the amended SOCIAL-OG-4 coverage canary still
 * runs): every OTHER image-less surface stays on the og-home fallback —
 * only the roadmap's commercial trio gets dedicated cards.
 */

const OG_DIR = resolve(__dirname, "../../../public/images/og");

/** The 6 P0-F surfaces: source file → its dedicated card (roadmap field 2). */
const DEDICATED_SURFACES: Array<[string, string]> = [
  ["src/app/(en)/memberships/layout.tsx", "og-memberships-en"],
  ["src/app/(ar)/ar/memberships/page.tsx", "og-memberships-ar"],
  ["src/app/(en)/evo/layout.tsx", "og-evo-en"],
  ["src/app/(ar)/ar/evo/layout.tsx", "og-evo-ar"],
  ["src/app/(en)/tools/layout.tsx", "og-tools-en"],
  ["src/app/(ar)/ar/tools/layout.tsx", "og-tools-ar"],
];

const GENERATOR = "scripts/generate-og-cards.py";
const ITEM_LIST_MODULE = "src/lib/tools-hub-itemlist.ts";
const EN_TOOLS_LAYOUT = "src/app/(en)/tools/layout.tsx";
const AR_TOOLS_LAYOUT = "src/app/(ar)/ar/tools/layout.tsx";

function repoRootPath(rel: string): string {
  return resolve(__dirname, "../../..", rel);
}

function read(rel: string): string {
  const p = repoRootPath(rel);
  expect(existsSync(p), `missing file: ${rel}`).toBe(true);
  return readFileSync(p, "utf8");
}

function pngDimensions(p: string): { w: number; h: number } {
  const buf = readFileSync(p);
  // PNG signature + IHDR: width at bytes 16-19, height at 20-23 (the visual
  // law canary decodes the full scanlines — the header read is enough here).
  expect(buf.subarray(0, 8).toString("hex")).toBe("89504e470d0a1a0a");
  return { w: buf.readUInt32BE(16), h: buf.readUInt32BE(20) };
}

describe("P0-F — the six dedicated cards exist on disk (1200×630, real PNG)", () => {
  it.each(DEDICATED_SURFACES)("card %s exists as a real PNG (non-trivial size)", (_rel, card) => {
    const p = resolve(OG_DIR, `${card}.png`);
    expect(existsSync(p), `${card}.png missing (run scripts/generate-og-cards.py)`).toBe(true);
    expect(statSync(p).size, `${card}.png looks empty`).toBeGreaterThan(10_000);
  });

  it.each(DEDICATED_SURFACES)("card %s is exactly 1200×630 (roadmap field 8)", (_rel, card) => {
    const { w, h } = pngDimensions(resolve(OG_DIR, `${card}.png`));
    expect(w).toBe(1200);
    expect(h).toBe(630);
  });

  it("the generator SPECS declare all six cards (regeneratable — never hand-baked)", () => {
    const gen = read(GENERATOR);
    for (const [_rel, card] of DEDICATED_SURFACES) {
      expect(gen, `SPECS missing ${card}`).toContain(`("${card}",`);
    }
  });

  it("the generator SPECS stay count-free (the TIMELESS baked-copy law)", () => {
    const gen = read(GENERATOR);
    const specs = gen.slice(gen.indexOf("SPECS = ["));
    expect(specs).not.toMatch(/868/);
    expect(specs).not.toMatch(/8830|8162/);
  });
});

describe("P0-F — the six surfaces reference their dedicated card (og + twitter)", () => {
  it.each(DEDICATED_SURFACES)("%s pins its dedicated card in og AND twitter", (rel, card) => {
    const src = read(rel);
    const needle = `/images/og/${card}.png?v=4`;
    const occurrences = src.split(needle).length - 1;
    // og image object + twitter images array = 2 wiring points.
    expect(occurrences, `${rel} must reference ${needle} (og + twitter)`).toBeGreaterThanOrEqual(2);
    expect(src).toContain('card: "summary_large_image"');
  });

  it.each(DEDICATED_SURFACES)("%s no longer shares the generic og-home card", (rel, _card) => {
    expect(read(rel)).not.toContain("/images/og/og-home-");
  });

  it("the og-home pair still exists (the fallback law for every other surface)", () => {
    expect(existsSync(resolve(OG_DIR, "og-home-en.png"))).toBe(true);
    expect(existsSync(resolve(OG_DIR, "og-home-ar.png"))).toBe(true);
  });
});

describe("P0-F — the tools-hub ItemList (both language trees)", () => {
  const enList = getToolsHubItemList("en");
  const arList = getToolsHubItemList("ar");

  it("both layouts import the ItemList module and emit its JSON-LD", () => {
    for (const rel of [EN_TOOLS_LAYOUT, AR_TOOLS_LAYOUT]) {
      const src = read(rel);
      expect(src).toContain('from "@/lib/tools-hub-itemlist"');
      expect(src).toContain("getToolsHubItemList(");
      expect(src).toContain('type="application/ld+json"');
      expect(src).toContain("jsonLd(toolsItemListSchema)");
    }
  });

  it("EN layout passes \"en\" and AR layout passes \"ar\" (the mirror law)", () => {
    expect(read(EN_TOOLS_LAYOUT)).toContain('getToolsHubItemList("en")');
    expect(read(AR_TOOLS_LAYOUT)).toContain('getToolsHubItemList("ar")');
  });

  it("the schema is a schema.org ItemList with 8 items, positions 1..8 sequential", () => {
    for (const list of [enList, arList]) {
      expect(list["@context"]).toBe("https://schema.org");
      expect(list["@type"]).toBe("ItemList");
      expect(list.name).toBeTruthy();
      expect(list.description).toBeTruthy();
      const items = list.itemListElement as Array<{ position: number; name: string; url: string }>;
      expect(items.length).toBe(8);
      expect(items.map((i) => i.position)).toEqual([1, 2, 3, 4, 5, 6, 7, 8]);
    }
  });

  it("EN items derive from TOOLS: nameEn + the hub grid's own href mapping (absolute)", () => {
    const items = enList.itemListElement as Array<{ name: string; url: string }>;
    TOOLS.forEach((tool, i) => {
      expect(items[i].name).toBe(tool.nameEn);
      const expected =
        tool.slug.startsWith("/")
          ? `https://alkemos.com${tool.slug}`
          : `https://alkemos.com/tools/${tool.slug}`;
      expect(items[i].url).toBe(expected);
    });
  });

  it("AR items derive from TOOLS: nameAr + /ar-prefixed mirrors (the SEO-GEO-4 law)", () => {
    const items = arList.itemListElement as Array<{ name: string; url: string }>;
    TOOLS.forEach((tool, i) => {
      expect(items[i].name).toBe(tool.nameAr);
      const expected =
        tool.slug.startsWith("/")
          ? `https://alkemos.com/ar${tool.slug}`
          : `https://alkemos.com/ar/tools/${tool.slug}`;
      expect(items[i].url).toBe(expected);
    });
  });

  it("every ItemList destination exists as a REAL route in both trees (no dead schema URLs)", () => {
    for (const list of [enList, arList]) {
      for (const item of list.itemListElement as Array<{ url: string }>) {
        const path = item.url.replace("https://alkemos.com", "");
        // EN paths resolve under src/app/(en)<path>; AR paths already
        // carry their /ar segment (src/app/(ar)/ar<path>).
        const candidates = [
          `src/app/(en)${path}/layout.tsx`,
          `src/app/(en)${path}/page.tsx`,
          `src/app/(ar)${path}/layout.tsx`,
          `src/app/(ar)${path}/page.tsx`,
        ];
        expect(
          candidates.some((c) => existsSync(repoRootPath(c))),
          `ItemList URL ${item.url} maps to no real route (${path})`,
        ).toBe(true);
      }
    }
  });

  it("the five calculator sub-layouts keep the og-home fallback law (P0-F scope: the HUB pair only)", () => {
    for (const rel of [
      "src/app/(en)/tools/bmi-calculator/layout.tsx",
      "src/app/(en)/tools/body-fat-calculator/layout.tsx",
      "src/app/(en)/tools/calorie-calculator/layout.tsx",
      "src/app/(en)/tools/macro-calculator/layout.tsx",
      "src/app/(en)/tools/water-tracker/layout.tsx",
      "src/app/(ar)/ar/tools/bmi-calculator/layout.tsx",
      "src/app/(ar)/ar/tools/body-fat-calculator/layout.tsx",
      "src/app/(ar)/ar/tools/calorie-calculator/layout.tsx",
      "src/app/(ar)/ar/tools/macro-calculator/layout.tsx",
      "src/app/(ar)/ar/tools/water-tracker/layout.tsx",
    ]) {
      expect(read(rel)).toContain("/images/og/og-home-");
    }
  });
});
